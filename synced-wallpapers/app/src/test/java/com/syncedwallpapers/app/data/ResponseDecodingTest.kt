/**
 * Decodes real server responses (generated by scripts/make-fixtures.sql from the
 * migrations) with the app's DTOs and JSON settings. Catches field-name and type
 * mismatches between the database and the app.
 */
class ResponseDecodingTest {
    private val json: Json = AppModule.json()
    private fun fx(name: String) = javaClass.classLoader!!.getResource("fixtures/$name.json")!!.readText()

    @Test fun `table rows decode`() {
        assertThat(json.decodeFromString<List<ProfileDto>>(fx("profiles")).map { it.name }).containsAtLeast("Asha", "Bala")
        assertThat(json.decodeFromString<List<ProfileDto>>(fx("profiles")).first { it.name == "Bala" }.phone).isEqualTo("+919812345678")
        assertThat(json.decodeFromString<List<GroupDto>>(fx("groups")).single().timeZone).isEqualTo("Asia/Kolkata")
        assertThat(json.decodeFromString<List<MemberDto>>(fx("group_members"))).hasSize(2)
        val proposals = json.decodeFromString<List<ProposalDto>>(fx("proposals"))
        assertThat(proposals.first { it.reminderText != null }.reminderStyle).isEqualTo(1)
        assertThat(proposals.map { it.status }).contains("APPROVED")
        assertThat(json.decodeFromString<List<AdminActionDto>>(fx("admin_actions")).single().type).isEqualTo("RENAME")
        assertThat(json.decodeFromString<List<TimeSuggestionDto>>(fx("time_suggestions"))).hasSize(1)
    }

    @Test fun `rpc results decode`() {
        assertThat(json.decodeFromString<InviteDto>(fx("create_invite")).code).hasLength(8)
        // Generated as the admin, who approved the join by inviting: nothing is waiting for them.
        assertThat(json.decodeFromString<List<PendingCounts>>(fx("my_pending_counts")).single().total).isEqualTo(0)
        json.decodeFromString<VoteSummary>(fx("proposal_vote_summary")).let { assertThat(it.approvals).isEqualTo(it.required) }
        assertThat(json.decodeFromString<AdminSummary>(fx("admin_action_summary")).status).isEqualTo("PENDING")
        assertThat(json.decodeFromString<List<JoinRequestRow>>(fx("group_join_requests")).single().name).isEqualTo("Chitra")
        assertThat(json.decodeFromString<List<Slot>>(fx("group_taken_slots")).size).isAtLeast(2)
        assertThat(json.decodeFromString<List<Commitment>>(fx("my_upcoming_commitments"))).isNotEmpty()
        assertThat(json.decodeFromString<DeliverySummary>(fx("delivery_summary")).people.single().name).isEqualTo("Bala")
        json.decodeFromString<List<Commitment>>(fx("proposal_conflicts"))
        assertThat(InstantSerializer.parse(json.decodeFromString<String>(fx("server_now")))).isNotNull()
        assertThat(json.decodeFromString<CreatedProposal>(fx("create_proposal")).imageReady).isFalse()
        val schedules = json.decodeFromString<List<ScheduleDto>>(fx("my_schedules"))
        assertThat(schedules.single().reminderText).isEqualTo("Happy Diwali")
        assertThat(schedules.single().deliveryMode).isEqualTo("AUTO")
        val preview = json.decodeFromString<JoinPreview>(fx("join_request_preview"))
        assertThat(preview.schedules).hasSize(1)
        assertThat(json.decodeFromString<List<MyJoinRequest>>(fx("my_join_requests")).single().groupName).isEqualTo("Family")
    }

    @Test fun `every queued notification decodes and has text`() {
        val rows = json.decodeFromString<List<OutboxDto>>(fx("notification_outbox"))
        assertThat(rows).isNotEmpty()
        val withoutText = rows.filter { EventTexts.forEvent(it.type, it.payload) == null }.map { it.type }.toSet()
        assertThat(withoutText - setOf("JOIN_STARTED", "LEFT_GROUP")).isEmpty()
        // Times in payloads parse as instants.
        rows.mapNotNull { it.payload["start_at"]?.jsonPrimitive?.content }.forEach { InstantSerializer.parse(it) }
    }
}
